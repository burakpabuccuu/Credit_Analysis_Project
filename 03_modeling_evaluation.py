# 1. Pipeline'lar için Ön İşleme (Preprocessing) Adımları
# Sayısal değişkenler için: Medyan doldurma ve Ölçeklendirme
numeric_transformer = Pipeline(steps=[
    ('imputer', SimpleImputer(strategy='median')),
    ('scaler', StandardScaler())
])

# Kategorik değişkenler (Dinamik listemiz) için: Mod ile doldurma ve One-Hot Encoding
categorical_transformer = Pipeline(steps=[
    ('imputer', SimpleImputer(strategy='most_frequent')),
    ('onehot', OneHotEncoder(handle_unknown='ignore', drop='first'))
])

# Lojistik Regresyon için ikisini birleştiriyoruz (ColumnTransformer)
preprocessor_lr = ColumnTransformer(
    transformers=[
        ('num', numeric_transformer, num_cols),
        ('cat', categorical_transformer, cat_cols)
    ])

# Ağaç modelleri (RF, LightGBM) yapıları gereği uzaklık hesaplamaz, OHE ve Scale'e ihtiyaç duymaz.
# Sadece eksik verileri medyan ile doldurmamız yeterlidir.
preprocessor_tree = Pipeline(steps=[
    ('imputer', SimpleImputer(strategy='median'))
])

# 2. Modellerin Pipeline İçinde Tanımlanması
