from sklearn.model_selection import GridSearchCV, cross_validate

# 1. Vahit Hoca'nın Klasik HPO Fonksiyonu (Pipeline Uyumlu Versiyon)
def hyperparameter_optimization(X, y, model_name, pipeline, params, cv_strategy, scoring="average_precision"):
    print(f"########## {model_name} Hiperparametre Optimizasyonu ##########")

    # Adım 1: Base (Varsayılan) Modelin Skoru
    cv_results = cross_validate(pipeline, X, y, cv=cv_strategy, scoring=scoring, n_jobs=-1)
    print(f"{scoring} (Before) : {round(cv_results['test_score'].mean(), 4)}")

    # Adım 2: GridSearchCV ile En İyi Parametreleri Arama
    # (Not: Vahit Hoca standartta GridSearchCV kullanır)
    search = GridSearchCV(
        estimator=pipeline,
        param_grid=params,
        cv=cv_strategy,
        scoring=scoring,
        n_jobs=-1,
        verbose=1
    ).fit(X, y)

    # Adım 3: En iyi parametreleri mevcut pipeline'a set etme
    pipeline.set_params(**search.best_params_)

    # Adım 4: Final (Tuned) Modelin Skoru
    cv_results_after = cross_validate(pipeline, X, y, cv=cv_strategy, scoring=scoring, n_jobs=-1)
    print(f"{scoring} (After)  : {round(cv_results_after['test_score'].mean(), 4)}")
    print(f"{model_name} Best Params : {search.best_params_}\n")

    return pipeline

# 2. LightGBM İçin Aranacak Parametre Izgarası (Grid)
