def grab_col_names(dataframe, cat_th=10, car_th=20):
    # object (string) tipinde olan kategorikler
    cat_cols = [col for col in dataframe.columns if dataframe[col].dtypes == "O"]

    # Sayısal görünüp aslında kategorik olanlar (Eşsiz değer sayısı cat_th'den küçük olanlar)
    num_but_cat = [col for col in dataframe.columns if dataframe[col].nunique() < cat_th and dataframe[col].dtypes != "O"]

    # Kategorik görünüp aslında kardinal (ID vb. eşsiz değeri çok yüksek) olanlar
    cat_but_car = [col for col in dataframe.columns if dataframe[col].nunique() > car_th and dataframe[col].dtypes == "O"]

    # Gerçek kategorikleri birleştir ve kardinalleri içinden çıkar
    cat_cols = cat_cols + num_but_cat
    cat_cols = [col for col in cat_cols if col not in cat_but_car]

    # Saf sayısal değişkenleri bul (num_but_cat olanları çıkar)
    num_cols = [col for col in dataframe.columns if dataframe[col].dtypes != "O"]
    num_cols = [col for col in num_cols if col not in num_but_cat]

    print(f"Observations (Gözlem Sayısı): {dataframe.shape[0]}")
    print(f"Variables (Değişken Sayısı): {dataframe.shape[1]}")
    print(f'cat_cols: {len(cat_cols)}')
    print(f'num_cols: {len(num_cols)}')
    print(f'cat_but_car: {len(cat_but_car)}')
    print(f'num_but_cat: {len(num_but_cat)}')

    return cat_cols, num_cols, cat_but_car

